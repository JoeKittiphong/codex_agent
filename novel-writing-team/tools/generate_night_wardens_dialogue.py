import re
from pathlib import Path

ROOT = Path('novel-writing-team/manuscript/projects/night-wardens')
SCENE_TEXT = ROOT.joinpath('scenes.md').read_text(encoding='utf-8')
MAP_TEXT = ROOT.joinpath('episode-map.md').read_text(encoding='utf-8')

scene_blocks = re.split(r'\n## Scene ', SCENE_TEXT)[1:]
scenes = {}
for block in scene_blocks:
    header, *rest = block.splitlines()
    sid = header.strip()
    data = {'id': sid}
    for line in rest:
        m = re.match(r'- ([^:]+):\s*(.*)', line)
        if m:
            data[m.group(1).strip()] = m.group(2).strip()
    ep = int(data['Episode'])
    scenes.setdefault(ep, []).append(data)

blocks = re.split(r'\n## ตอนที่ ', MAP_TEXT)[1:]
episodes = []
for block in blocks:
    lines = block.splitlines()
    m = re.match(r'(\d+):\s*(.+)', lines[0])
    if not m:
        continue
    ep = int(m.group(1))
    title = m.group(2).strip()
    data = {'ep': ep, 'title': title}
    for line in lines[1:]:
        m2 = re.match(r'- ([^:]+):\s*(.*)', line)
        if m2:
            data[m2.group(1).strip()] = m2.group(2).strip()
    episodes.append(data)


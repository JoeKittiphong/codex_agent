def pick(seq, n):
    return seq[n % len(seq)]


def get_voice(name, key):
    return VOICE.get(name, {}).get(key) or (DEFAULT_REPLY if key == 'reply' else DEFAULT_MURMUR)


def list_chars(chars: str):
    return [x.strip() for x in chars.split(',') if x.strip()]


def second_char(chars: str, pov: str):
    banned = ['ทีม', 'มวลทมิฬ', 'ฝันร้าย', 'เงาดำ', 'เจ้าแก่น', 'มอรัส', 'คนงาน', 'คนไข้เงา']
    for name in list_chars(chars):
        if name == pov:
            continue
        if any(b in name for b in banned):
            continue
        return name
    return ''


def setting_sense(setting: str, ep: int):
    if any(k in setting for k in ['ฝัน', 'แดนนิทรา', 'มหานครไร้รุ่ง']):
        return pick(DREAM_SENSE, ep)
    for k, v in REAL_SENSE.items():
        if k != 'default' and k in setting:
            return v
    return REAL_SENSE['default']


def real_or_dream_label(setting: str):
    if any(k in setting for k in ['ฝัน', 'แดนนิทรา', 'มหานครไร้รุ่ง']):
        return 'โลกฝัน'
    return 'โลกจริง'



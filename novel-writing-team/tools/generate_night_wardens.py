def pick(seq, n):
    return seq[n % len(seq)]


def other_char(chars: str, pov: str):
    parts = [x.strip() for x in chars.split(',') if x.strip()]
    for p in parts:
        if p != pov:
            return p
    return None


def setting_sense(setting: str, ep: int):
    if 'ฝัน' in setting or 'แดนนิทรา' in setting or 'มหานครไร้รุ่ง' in setting:
        return pick(DREAM_SENSE, ep)
    return pick(REAL_SENSE, ep)


